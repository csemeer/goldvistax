export function getInstrumentById(id: InstrumentId): CanonicalInstrument {
  const inst = CANONICAL_COMMODITY_REGISTRY[id];
  if (!inst) {
    throw new Error(`Unknown instrument ID: ${id}`);
  }
  return inst;
}

export function getPrimaryInstrumentForCommodity(commodity: CommodityType): CanonicalInstrument {
  switch (commodity) {
    case 'GOLD':
      return CANONICAL_COMMODITY_REGISTRY.XAUUSD;
    case 'SILVER':
      return CANONICAL_COMMODITY_REGISTRY.XAGUSD;
    case 'WTI_OIL':
      return CANONICAL_COMMODITY_REGISTRY.WTI_CRUDE;
    case 'BRENT_OIL':
      return CANONICAL_COMMODITY_REGISTRY.BRENT_CRUDE;
  }
}

export function getCommodityFamily(commodity: CommodityType): 'PRECIOUS_METALS' | 'ENERGY' {
  return commodity === 'GOLD' || commodity === 'SILVER' ? 'PRECIOUS_METALS' : 'ENERGY';
}
